#!/usr/bin/env bun
// Pre-render every Beeswax line (lines/lines.json) with the designed voice (paid; needs ELEVENLABS_API_KEY
// and ELEVENLABS_VOICE_ID). Existing files are skipped unless --force.
//   bun scripts/prerender.ts [--force] [--only id,id] [--model eleven_flash_v2_5] [--concurrency 2] [--dry-run]
// Writes to hive/out/ (git-ignored):
//   unity/<id>.mp3               every line, mp3 44.1 kHz 128 kbps (Unity imports mp3; the Hive can serve ear ones at /audio/<id>.mp3)
//   glasses/pcm/<id>.pcm         ear lines as PCM16 LE mono 16 kHz (render cache for the bundle below)
//   glasses/lines.generated.ts   { [id]: base64 PCM16 } for the miniapp's speaker createStream
//   manifest.json                id -> channel, caption, beat, duration_s, files
// Default model matches the live voice (Flash v2.5) so pre-rendered and live lines sound alike;
// --model eleven_multilingual_v2 gives higher quality.
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { parseArgs } from "node:util";
import { LINES, type Line } from "../src/lines";
import { TTS_MODEL, TTS_SAMPLE_RATE, ttsAvailable, ttsBytes } from "../src/tts";

const HIVE = resolve(import.meta.dir, "..");
const OUT = join(HIVE, "out");
const UNITY = join(OUT, "unity");
const PCM = join(OUT, "glasses", "pcm");
const MP3_KBPS = 128;

const { values: args } = parseArgs({
  options: {
    force: { type: "boolean", default: false },
    only: { type: "string" },
    model: { type: "string", default: TTS_MODEL },
    concurrency: { type: "string", default: "2" },
    "dry-run": { type: "boolean", default: false },
  },
});

interface Job { line: Line; kind: "mp3" | "pcm"; file: string }

const mp3Path = (id: string) => join(UNITY, `${id}.mp3`);
const pcmPath = (id: string) => join(PCM, `${id}.pcm`);
const size = (file: string) => (existsSync(file) ? statSync(file).size : 0);

function plan(lines: Line[]): Job[] {
  const jobs: Job[] = [];
  for (const line of lines) {
    const wanted: Job[] = [{ line, kind: "mp3", file: mp3Path(line.id) }];
    if (line.channel === "ear") wanted.push({ line, kind: "pcm", file: pcmPath(line.id) });
    for (const job of wanted) if (args.force || size(job.file) === 0) jobs.push(job);
  }
  return jobs;
}

async function render(job: Job): Promise<void> {
  const audio = await ttsBytes(job.line.text, {
    format: job.kind === "mp3" ? "mp3_44100_128" : "pcm_16000",
    model: args.model,
    timeoutMs: 60_000,
  });
  // PCM16 must be whole samples
  writeFileSync(job.file, job.kind === "pcm" && audio.length % 2 ? audio.subarray(0, audio.length - 1) : audio);
}

async function pool<T>(items: T[], n: number, fn: (item: T) => Promise<void>): Promise<void> {
  let next = 0;
  const worker = async () => {
    while (next < items.length) await fn(items[next++]!);
  };
  await Promise.all(Array.from({ length: Math.max(1, Math.min(n, items.length)) }, worker));
}

/** Rebuild the manifest and glasses bundle from whatever is on disk. */
function writeOutputs(lines: Line[]): void {
  const manifest: Record<string, unknown> = {};
  const bundle: string[] = [];
  for (const line of lines) {
    const mp3 = size(mp3Path(line.id));
    const pcm = size(pcmPath(line.id));
    // PCM length is exact; CBR mp3 length is a close estimate
    const duration = pcm ? pcm / 2 / TTS_SAMPLE_RATE : mp3 ? (mp3 * 8) / (MP3_KBPS * 1000) : null;
    manifest[line.id] = {
      channel: line.channel,
      caption: line.text,
      beat: line.beat ?? null,
      tags: line.tags ?? [],
      duration_s: duration === null ? null : Math.round(duration * 100) / 100,
      mp3: mp3 ? `unity/${line.id}.mp3` : null,
      pcm: pcm ? `glasses/pcm/${line.id}.pcm` : null,
    };
    if (pcm) bundle.push(`  ${JSON.stringify(line.id)}: ${JSON.stringify(readFileSync(pcmPath(line.id)).toString("base64"))},`);
  }
  writeFileSync(
    join(OUT, "manifest.json"),
    JSON.stringify({ generated_at: new Date().toISOString(), model: args.model, voice_id: process.env.ELEVENLABS_VOICE_ID ?? null, lines: manifest }, null, 2),
  );
  const ts = [
    "// GENERATED by hive/scripts/prerender.ts. Do not edit.",
    `// Beeswax ear lines: base64 PCM16 little-endian mono at ${TTS_SAMPLE_RATE} Hz, for speaker createStream.`,
    `export const SAMPLE_RATE = ${TTS_SAMPLE_RATE};`,
    "export const LINE_PCM16: Record<string, string> = {",
    ...bundle,
    "};",
    "export default LINE_PCM16;",
    "",
  ].join("\n");
  writeFileSync(join(OUT, "glasses", "lines.generated.ts"), ts);
  console.log(`Wrote out/manifest.json and out/glasses/lines.generated.ts (${bundle.length} ear lines, ${(ts.length / 1e6).toFixed(2)} MB)`);
}

async function main(): Promise<void> {
  const only = args.only?.split(",").map((s) => s.trim()).filter(Boolean);
  const unknown = only?.filter((id) => !LINES[id]) ?? [];
  if (unknown.length) throw new Error(`unknown line ids: ${unknown.join(", ")}`);
  const lines = Object.values(LINES).filter((l) => !only || only.includes(l.id));
  const jobs = plan(lines);
  const chars = jobs.reduce((n, j) => n + j.line.text.length, 0);
  console.log(`${lines.length} lines, ${jobs.length} renders to do (${chars} characters) with ${args.model}`);

  if (args["dry-run"]) {
    for (const j of jobs) console.log(`  ${j.kind}  ${j.line.id}  "${j.line.text}"`);
    return;
  }
  if (!ttsAvailable()) throw new Error("set ELEVENLABS_API_KEY and ELEVENLABS_VOICE_ID (hive/.env) first");
  mkdirSync(UNITY, { recursive: true });
  mkdirSync(PCM, { recursive: true });

  const failed: string[] = [];
  let done = 0;
  await pool(jobs, Math.max(1, Number(args.concurrency) || 2), async (job) => {
    try {
      await render(job);
      console.log(`  [${++done}/${jobs.length}] ${job.kind} ${job.line.id}`);
    } catch (e) {
      failed.push(`${job.kind}:${job.line.id}`);
      console.error(`  FAILED ${job.kind} ${job.line.id}: ${e instanceof Error ? e.message : String(e)}`);
    }
  });
  writeOutputs(Object.values(LINES));
  if (failed.length) {
    console.error(`${failed.length} renders failed: ${failed.join(", ")}. Re-run to retry just those.`);
    process.exit(1);
  }
}

if (import.meta.main) {
  main().catch((e) => {
    console.error(`prerender failed: ${e instanceof Error ? e.message : String(e)}`);
    process.exit(1);
  });
}
