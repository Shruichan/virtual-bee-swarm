    /// <summary>
    /// Builds Scenes/VirtualBeeSwarm.unity (next to VirtualBeeSwarm.asmdef) from code: every system wired, primitive
    /// placeholders, unlit materials. Reproducible in batchmode:
    ///   Unity -batchmode -nographics -projectPath P -executeMethod VirtualBeeSwarm.Editor.BuildGameScene.Build -quit -logFile build.log
    /// Materials / meshes / textures are created only if missing, so tweaks to them survive a rebuild; the scene
    /// itself is regenerated (the old one is copied to Library/SceneBackups/ first).
    /// XR rig: the root objects of the rig template Scenes/RigTemplate.unity (OVRCameraRig + passthrough underlay +
    /// boundary suppression + mic/scene permission requests, made by ProjectBootstrap) are copied in, then
    /// VirtualBeeSwarm.Meta.Editor.MetaRigWiring (if the Meta SDK is installed) adds the OVRHands and wires
    /// OvrHandPoseSource / OvrPassthroughDimmer. Edit rig settings in RigTemplate.unity, not here.
    /// The main scene becomes the only scene in Build Settings. World layout: the TableAnchor sits on the table top,
    /// the player stands at -Z looking +Z (DesktopTestCamera switches itself off in the headset).
    /// VirtualBeeSwarm.unity is a BUILD OUTPUT: git-ignored, regenerated by this builder (GameBuild.BuildApk runs it
    /// first, SceneAutoBuild runs it when the project opens without the scene). Only its .meta is tracked, and the
    /// builder pins that GUID (SceneGuid), so Build Settings stay the same on every machine. Never hand-edit the scene.
    /// </summary>
    public static class BuildGameScene
    {
        public const string SceneName = "VirtualBeeSwarm.unity";
        /// <summary>The main scene's GUID, as in its tracked .meta and in ProjectSettings/EditorBuildSettings.asset.</summary>
        public const string SceneGuid = "ed6503827dca69c6db76a5f955666566";
        const string OfflineSceneName = "OfflineTest.unity";
        /// <summary>Rig template (relative to the VirtualBeeSwarm folder): its root objects are copied into the main scene.</summary>
        const string RigTemplateScene = "Scenes/RigTemplate.unity";
        const string BackupDir = "Library/SceneBackups";

        static string _root;          // e.g. Assets/VirtualBeeSwarm
        static Font _font;
        static Mesh _hexMesh, _hexSmall;
        static readonly Dictionary<string, Material> Mats = new Dictionary<string, Material>();

        /// <summary>Project-relative path of the main scene (Assets/VirtualBeeSwarm/Scenes/VirtualBeeSwarm.unity).</summary>
        public static string MainScenePath => FindRoot() + "/Scenes/" + SceneName;

        [MenuItem("Virtual Bee Swarm/Build Scene")]
        public static void BuildMenu()
        {
            // Batch mode never asks (there's nobody to answer); the editor asks before it throws the old scene away.
            if (!Application.isBatchMode)
            {
                string existing = MainScenePath;
                if (File.Exists(existing) && !EditorUtility.DisplayDialog("Rebuild " + SceneName + "?",
                        "This regenerates " + existing + " from code. Hand edits in the scene are lost (a copy goes to " +
                        BackupDir + "/). Prefabs, materials and meshes are kept.", "Rebuild", "Cancel"))
                    return;
                if (!EditorSceneManager.SaveCurrentModifiedScenesIfUserWantsTo()) return;
            }
            BuildAt(SceneName, offline: false, exitWhenBatch: false);
        }

        /// <summary>Builds the main scene (no prompt) and returns its path. Throws on failure. GameBuild and
        /// SceneAutoBuild call this.</summary>
        public static string BuildMain()
        {
            string path = BuildScene(SceneName, offline: false);
            Debug.Log("[VBS] scene built: " + path);
            return path;
        }

        [MenuItem("Virtual Bee Swarm/Build Offline Test Scene (no network, no mic)")]
        public static void BuildOfflineMenu() => BuildAt(OfflineSceneName, offline: true, exitWhenBatch: false);

        /// <summary>-executeMethod entry point (exit code 1 on failure in batchmode).</summary>
        public static void Build() => BuildAt(SceneName, offline: false, exitWhenBatch: true);

        /// <summary>-executeMethod: the same scene, but GameNet forced offline, the bus never connects, no HumDetector.</summary>
        public static void BuildOffline() => BuildAt(OfflineSceneName, offline: true, exitWhenBatch: true);

        static void BuildAt(string sceneFile, bool offline, bool exitWhenBatch)
        {
            try
            {
                string path = BuildScene(sceneFile, offline);
                Debug.Log("[VBS] scene built: " + path);
            }
            catch (Exception e)
            {
                Debug.LogError("[VBS] scene build FAILED: " + e);
                if (exitWhenBatch && Application.isBatchMode) EditorApplication.Exit(1);
                throw;
            }
        }

        // =====================================================================================================
        public static string BuildScene(string sceneFile, bool offline) => BuildScene(sceneFile, offline, withRig: !offline);

