        /// <summary>Set a serialized field by name; throws if it doesn't exist (catches renames at build time).</summary>
        static void Set(Object target, string field, object value)
        {
            var so = new SerializedObject(target);
            var p = so.FindProperty(field);
            if (p == null) throw new Exception(target.GetType().Name + "." + field + " is not a serialized field");
            switch (value)
            {
                case null: p.objectReferenceValue = null; break;
                case Object[] arr:
                    p.arraySize = arr.Length;
                    for (int i = 0; i < arr.Length; i++) p.GetArrayElementAtIndex(i).objectReferenceValue = arr[i];
                    break;
                case Object o: p.objectReferenceValue = o; break;
                case bool b: p.boolValue = b; break;
                case float f: p.floatValue = f; break;
                case int n: p.intValue = n; break;
                case string s: p.stringValue = s; break;
                case Enum e: p.intValue = Convert.ToInt32(e); break;
                default: throw new Exception("unsupported value type for " + field + ": " + value.GetType());
            }
            so.ApplyModifiedPropertiesWithoutUndo();
        }

        /// <summary>Sanity checks on the saved scene (logged; throws on a broken build).</summary>
        static void Validate(Scene scene, int behaviourCount, bool withRig)
        {
            int missing = 0, components = 0;
            foreach (var root in scene.GetRootGameObjects())
            {
                foreach (var c in root.GetComponentsInChildren<Component>(true))
                {
                    if (c == null) { missing++; continue; }
                    components++;
                }
            }
            var director = Object.FindAnyObjectByType<GameDirector>(FindObjectsInactive.Include);
            var so = new SerializedObject(director);
            int listed = so.FindProperty("behaviours").arraySize;
            var sample = Object.FindAnyObjectByType<BeeswaxController>(FindObjectsInactive.Include)?.GetComponentInChildren<TextMesh>(true);
            string textInfo = sample != null ? " caption font=" + (sample.font != null ? sample.font.name : "NONE") : "";
            Debug.Log("[VBS] validate: " + components + " components, " + missing + " missing scripts, director lists " +
                      listed + "/" + behaviourCount + " beat behaviours, shader " +
                      (Shader.Find(GameMaterials.ShaderName) != null ? "OK" : "MISSING (fallback used)") + textInfo);
            int rigs = 0;
            var rigType = Type.GetType("OVRCameraRig, Oculus.VR");
            if (rigType != null) rigs = Object.FindObjectsByType(rigType, FindObjectsInactive.Include, FindObjectsSortMode.None).Length;
            Debug.Log("[VBS] validate: OVRCameraRig x" + rigs + (rigType == null ? " (Meta SDK not installed)" : ""));
            if (missing > 0 || listed != behaviourCount) throw new Exception("scene validation failed");
            if (withRig && rigType != null && rigs != 1) throw new Exception("scene validation failed: expected 1 OVRCameraRig, found " + rigs);
        }
