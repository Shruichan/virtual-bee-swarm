        /// <summary>Copies the rig template's root objects (OVRCameraRig + passthrough, light) into the new scene.</summary>
        static string MergeRigTemplate(Scene scene)
        {
            string template = _root + "/" + RigTemplateScene;
            if (!File.Exists(template))
            {
                Debug.LogWarning("[VBS] rig template " + template + " not found: the scene gets NO XR rig. " +
                                 "Run Virtual Bee Swarm > Bootstrap Project Settings (it creates the template), then rebuild.");
                return "MISSING (no " + template + ")";
            }
            var rigScene = EditorSceneManager.OpenScene(template, OpenSceneMode.Additive);
            var names = new List<string>();
            foreach (var go in rigScene.GetRootGameObjects())
            {
                names.Add(go.name);
                // Keep the authored lid visible when a player leans in to inspect or grip the hive.
                foreach (var camera in go.GetComponentsInChildren<Camera>(true))
                    camera.nearClipPlane = Mathf.Min(camera.nearClipPlane, 0.025f);
            }
            EditorSceneManager.MergeScenes(rigScene, scene); // moves the objects; the template file is not changed
            SceneManager.SetActiveScene(scene);
            return "from " + template + " [" + string.Join(", ", names) + "]";
        }

        /// <summary>Hands + rig refs through VirtualBeeSwarm.Meta.Editor (only compiled with the Meta XR Core SDK).</summary>
        static string WireMetaRig(GameObject inputRoot)
        {
            var wiring = Type.GetType("VirtualBeeSwarm.Meta.Editor.MetaRigWiring, VirtualBeeSwarm.Meta.Editor");
            var wire = wiring?.GetMethod("Wire", new[] { typeof(GameObject) });
            if (wire == null) return "Meta wiring not available (no com.meta.xr.sdk.core): hands/passthrough not wired";
            return (string)wire.Invoke(null, new object[] { inputRoot });
        }

        /// <summary>
        /// Makes the main scene keep SceneGuid. Its .meta is tracked but the .unity isn't, and Unity deletes a .meta whose
        /// asset is missing (a fresh clone), so write the .meta back before the scene is saved: the import then reads
        /// the GUID from it. A scene that already exists under another GUID is deleted first (it was backed up).
        /// </summary>
        static void PinSceneGuid(string scenePath)
        {
            string meta = scenePath + ".meta";
            string existing = AssetDatabase.AssetPathToGUID(scenePath, AssetPathToGUIDOptions.OnlyExistingAssets);
            if (existing == SceneGuid) return;
            if (!string.IsNullOrEmpty(existing))
            {
                Debug.LogWarning("[VBS] " + scenePath + " has GUID " + existing + ": re-creating it as " + SceneGuid);
                AssetDatabase.DeleteAsset(scenePath);
            }
            string other = AssetDatabase.GUIDToAssetPath(SceneGuid);
            if (!string.IsNullOrEmpty(other) && other != scenePath && File.Exists(other))
                throw new Exception("GUID " + SceneGuid + " is already used by " + other);
            File.WriteAllText(meta,
                "fileFormatVersion: 2\nguid: " + SceneGuid + "\nDefaultImporter:\n  externalObjects: {}\n  userData: \n" +
                "  assetBundleName: \n  assetBundleVariant: \n");
        }

        static void BackupExisting(string scenePath)
        {
            if (!File.Exists(scenePath)) return;
            Directory.CreateDirectory(BackupDir);
            string dest = BackupDir + "/" + Path.GetFileNameWithoutExtension(scenePath) + "-" + DateTime.Now.ToString("yyyyMMdd-HHmmss") + ".unity";
            File.Copy(scenePath, dest, true);
            Debug.Log("[VBS] previous " + scenePath + " copied to " + dest);
        }

