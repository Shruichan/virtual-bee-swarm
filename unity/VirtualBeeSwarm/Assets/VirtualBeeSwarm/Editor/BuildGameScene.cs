        static void Mat(string name, Color c, GameMaterials.Blend blend, bool vertexColors = false, bool doubleSided = false,
            float emission = 1f, Texture texture = null)
        {
            string path = _root + "/Materials/" + name + ".mat";
            var m = AssetDatabase.LoadAssetAtPath<Material>(path);
            if (m == null)
            {
                m = GameMaterials.Create(name, c, blend, vertexColors, emission, instancing: true, doubleSided: doubleSided);
                if (texture != null)
                {
                    if (m.HasProperty(GameMaterials.MainTexId)) m.SetTexture(GameMaterials.MainTexId, texture);
                    if (m.HasProperty(GameMaterials.BaseMapId)) m.SetTexture(GameMaterials.BaseMapId, texture);
                }
                AssetDatabase.CreateAsset(m, path);
            }
            Mats[name] = m;
        }

        static Material M(string name)
        {
            if (Mats.TryGetValue(name, out var m)) return m;
            throw new Exception("material not created: " + name);
        }

        static Mesh LoadOrCreateMesh(string name, Func<Mesh> create)
        {
            string path = _root + "/Meshes/" + name + ".asset";
            var mesh = AssetDatabase.LoadAssetAtPath<Mesh>(path);
            if (mesh != null) return mesh;
            mesh = create();
            AssetDatabase.CreateAsset(mesh, path);
            return mesh;
        }

        static Texture2D LoadOrCreateTexture(string name, Func<Texture2D> create)
        {
            string path = _root + "/Materials/" + name + ".asset";
            var tex = AssetDatabase.LoadAssetAtPath<Texture2D>(path);
            if (tex != null) return tex;
            tex = create();
            AssetDatabase.CreateAsset(tex, path);
            return tex;
        }

